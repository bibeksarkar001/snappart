"""Write docs/licences.md: every package installed in the active environment with its licence. Python packages: from their metadata
(License-Expression, then License, then classifiers, then the conda record). Native conda packages: from conda-meta. Run with the project
environment active: `python scripts/licences.py`."""
import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECT = {"fastapi", "uvicorn", "pydantic", "pydantic-settings", "httpx", "openai", "python-multipart", "jsonschema", "numpy", "scipy",
          "opencv-python", "opencv-contrib-python", "pillow", "cadquery", "scikit-image", "trimesh", "pytest"}


CONDA = {}
for f in (Path(sys.prefix) / "conda-meta").glob("*.json"):
    r = json.loads(f.read_text())
    CONDA[r["name"].lower()] = (r["name"], r["version"], r.get("license") or "not stated")


def licence(d) -> str:
    m = d.metadata
    if m.get("License-Expression"):
        return m["License-Expression"]
    lic = (m.get("License") or "").strip()
    first = lic.splitlines()[0].strip() if lic else ""
    if first and len(first) < 60 and first.upper() != "UNKNOWN":
        return first
    cls = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
    if cls:
        return "; ".join(cls)
    name = m["Name"].lower()
    return CONDA.get(name, CONDA.get(name.replace("-", "_"), (0, 0, "not stated")))[2]


rows = {}
for d in metadata.distributions():
    name = d.metadata["Name"]
    if name:
        rows[name.lower()] = (name, d.version, licence(d))
lines = ["# Licences of Python dependencies", "",
         "Generated by `scripts/licences.py` from the installed packages' own metadata (not reviewed by a lawyer). **Bold** rows are direct",
         "dependencies of the backend; the rest come in through them. The BIP-39 word list in `backend/app/wordlist.txt` is MIT (via",
         "@scure/bip39). `meta-sam-parser` is under Meta's SAM License (its own terms, not an open-source licence), copied to",
         "`third_party/meta-sam-parser/LICENSE`. FFmpeg (GPL-2.0-or-later) is installed by conda as a dependency of VTK and is used for voice",
         "conversion only if present; this repository does not redistribute it.",
         "", "## Python packages", "", "| Package | Version | Licence |", "|---|---|---|"]
for key in sorted(rows):
    name, ver, lic = rows[key]
    b = "**" if key in DIRECT else ""
    lines.append(f"| {b}{name}{b} | {ver} | {re.sub(r'[|]', '/', lic)} |")
py = {k.replace("_", "-") for k in rows}
native = sorted(k for k in CONDA if k.replace("_", "-") not in py)
lines += ["", "## Native packages (conda, no Python metadata)", "", "| Package | Version | Licence |", "|---|---|---|"]
lines += [f"| {CONDA[k][0]} | {CONDA[k][1]} | {re.sub(r'[|]', '/', CONDA[k][2])} |" for k in native]
(ROOT / "docs" / "licences.md").write_text("\n".join(lines) + "\n")
print(f"{len(rows)} Python and {len(native)} native packages -> docs/licences.md")
